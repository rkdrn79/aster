// Rebuilds src/research-harness/vendor/mathjax/tex-svg.mjs: MathJax 3.2.2 (Apache-2.0), TeX input
// to self-contained SVG paths, bundled into one module so the Figure kit typesets math on any host
// without fonts or native dependencies. Run: node config/scripts/vendor-figure-mathjax.mjs
import { execFileSync } from 'node:child_process'
import { mkdirSync, mkdtempSync, rmSync, writeFileSync, copyFileSync } from 'node:fs'
import os from 'node:os'
import path from 'node:path'

const VERSION = '3.2.2'
const root = path.resolve(import.meta.dirname, '../..')
const out = path.join(root, 'src/research-harness/vendor/mathjax')
const work = mkdtempSync(path.join(os.tmpdir(), 'aster-mathjax-'))
try {
  const pkg = path.join(work, 'node_modules/mathjax-full')
  mkdirSync(pkg, { recursive: true })
  const tarball = path.join(work, 'mathjax.tgz')
  execFileSync('curl', [
    '-sSfL',
    '-o',
    tarball,
    `https://registry.npmjs.org/mathjax-full/-/mathjax-full-${VERSION}.tgz`
  ])
  execFileSync('tar', ['-xzf', tarball, '-C', pkg, '--strip-components=1'])
  const entry = path.join(work, 'entry.mjs')
  writeFileSync(
    entry,
    `import { mathjax } from 'mathjax-full/js/mathjax.js'
import { TeX } from 'mathjax-full/js/input/tex.js'
import { SVG } from 'mathjax-full/js/output/svg.js'
import { liteAdaptor } from 'mathjax-full/js/adaptors/liteAdaptor.js'
import { RegisterHTMLHandler } from 'mathjax-full/js/handlers/html.js'
import 'mathjax-full/js/input/tex/base/BaseConfiguration.js'
import 'mathjax-full/js/input/tex/ams/AmsConfiguration.js'
import 'mathjax-full/js/input/tex/newcommand/NewcommandConfiguration.js'
import 'mathjax-full/js/input/tex/boldsymbol/BoldsymbolConfiguration.js'
const adaptor = liteAdaptor()
RegisterHTMLHandler(adaptor)
const document = mathjax.document('', {
  InputJax: new TeX({ packages: ['base', 'ams', 'newcommand', 'boldsymbol'] }),
  OutputJax: new SVG({ fontCache: 'none' })
})
export function texToSvg(tex, display = false) {
  return adaptor.outerHTML(adaptor.firstChild(document.convert(tex, { display })))
}
`
  )
  const bundle = path.join(out, 'tex-svg.mjs')
  execFileSync(path.join(root, 'node_modules/.bin/esbuild'), [
    entry,
    '--bundle',
    '--platform=node',
    '--format=esm',
    '--minify',
    '--legal-comments=none',
    `--banner:js=/* MathJax ${VERSION} (https://www.mathjax.org), Apache License 2.0; see LICENSE beside this file. Generated by config/scripts/vendor-figure-mathjax.mjs. */`,
    `--outfile=${bundle}`
  ])
  copyFileSync(path.join(pkg, 'LICENSE'), path.join(out, 'LICENSE'))
} finally {
  rmSync(work, { recursive: true, force: true })
}
